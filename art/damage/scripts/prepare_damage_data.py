"""Generate deterministic gameplay/art bindings for the existing 36 city slots."""
from pathlib import Path
import copy,math
import xml.etree.ElementTree as ET
repo=Path(__file__).resolve().parents[3];mod=repo/'mod'
SLOTS=36
def write(tree,path):
    ET.indent(tree);tree.write(path,encoding='utf-8',xml_declaration=True)
def name(n,d,m,s,legacy):return f'BUILDING_BS_DAMAGED_{n}_{d}_M{m}_S{s}'+('_L'if legacy else '')
variants=[(name(n,d,m,s,legacy),n,d,m,s,legacy)for n in (1,2,3)for d in range(6)for m in range(1,1<<n)for s in range(1,SLOTS+1)for legacy in (0,1)]
sql=['-- Generated by art/damage/scripts/prepare_damage_data.py',
     'CREATE TEMP TABLE BS_DamageTypes(Type TEXT, Span INTEGER, Direction INTEGER, Mask INTEGER, Slot INTEGER, Legacy INTEGER);',
     'INSERT INTO BS_DamageTypes VALUES\n'+',\n'.join(f"('{t}',{n},{d},{m},{s},{legacy})"for t,n,d,m,s,legacy in variants)+';',
     "INSERT INTO Types(Type,Kind) SELECT Type,'KIND_BUILDING' FROM BS_DamageTypes;",
     "INSERT INTO Buildings(BuildingType,Name,Description,PrereqDistrict,Cost,RequiresPlacement,InternalOnly,IsWonder,AdvisorType) SELECT Type,'LOC_DISTRICT_BS_'||Span||'_NAME','LOC_DISTRICT_BS_DESCRIPTION','DISTRICT_BS_BRIDGE_'||Span||CASE WHEN Legacy=1 THEN '' ELSE '_D'||Direction END,1,0,1,0,'ADVISOR_GENERIC' FROM BS_DamageTypes;",
     'INSERT INTO Buildings_XP2(BuildingType,Bridge) SELECT Type,1 FROM BS_DamageTypes;',
     "INSERT INTO BuildingModifiers(BuildingType,ModifierId) SELECT T.Type,M.ModifierId FROM BS_DamageTypes T JOIN BuildingModifiers M ON M.BuildingType='BUILDING_BS_DECK_'||T.Span||'_'||T.Direction;",
     'DROP TABLE BS_DamageTypes;']
icons=[]
for n in (1,2,3):
    for slot in range(1,SLOTS+1):
        permit=f'BUILDING_BS_REPAIR_{n}_S{slot}';project=f'PROJECT_BS_REPAIR_{n}_S{slot}';tag=f'LOC_{project}_NAME'
        sql.extend([f"INSERT INTO Types(Type,Kind) VALUES('{permit}','KIND_BUILDING'),('{project}','KIND_PROJECT');",
            f"INSERT INTO Buildings(BuildingType,Name,Cost,InternalOnly,PrereqDistrict) VALUES('{permit}','{tag}',1,1,'DISTRICT_CITY_CENTER');",
            f"INSERT INTO Projects(ProjectType,Name,ShortName,Description,Cost,CostProgressionModel,RequiredBuilding,AdvisorType) VALUES('{project}','{tag}','{tag}','LOC_BS_REPAIR_DESCRIPTION',{math.ceil(81*n*.4)},'NO_COST_PROGRESSION','{permit}','ADVISOR_GENERIC');"])
        icons.append(f"INSERT INTO IconDefinitions(Name,Atlas,\"Index\") VALUES('ICON_{project}','ICON_ATLAS_BS_BRIDGE_DISTRICTS',{0 if n==1 else 1});")
(mod/'Damage.sql').write_text('\n'.join(sql)+'\n',encoding='utf8')
(mod/'DamageIcons.sql').write_text('\n'.join(icons)+'\n',encoding='utf8')
text=ET.Element('GameData');localized=ET.SubElement(text,'LocalizedText')
for language in ('zh_Hans_CN','en_US'):
    zh=language=='zh_Hans_CN'
    rows={'LOC_BS_REPAIR_DESCRIPTION':('修复这座桥的全部受损桥段，恢复桥面外观与通行能力。' if zh else 'Repair all damaged segments of this bridge and restore its appearance and crossing.'),
          'LOC_BS_REPAIR_POSITION':('修复{1_Num}格桥（{2_Num}, {3_Num}）' if zh else 'Repair {1_Num}-tile bridge ({2_Num}, {3_Num})')}
    for n in (1,2,3):
        for slot in range(1,SLOTS+1):rows[f'LOC_PROJECT_BS_REPAIR_{n}_S{slot}_NAME']=(f'修复{n}格桥 #{slot}'if zh else f'Repair {n}-tile bridge #{slot}')
    for tag,value in rows.items():ET.SubElement(ET.SubElement(localized,'Row',Tag=tag,Language=language),'Text').text=value
write(ET.ElementTree(text),mod/'DamageText.xml')
art=ET.parse(mod/'ArtDefs/WonderMovie.artdef');collection=art.find('m_RootCollections/Element')
templates={e.find('m_Name').get('text'):e for e in collection.findall('Element')}
for e in list(collection.findall('Element')):
    if e.find('m_Name').get('text').startswith('BUILDING_BS_DAMAGED_'):collection.remove(e)
for t,n,d,m,s,legacy in variants:
    e=copy.deepcopy(templates[f'BUILDING_BS_DECK_{n}_{d}'+(''if legacy else '_AXIS')])
    e.find('m_Name').set('text',t)
    for node in e.iter():
        if node.tag=='m_EntryName':node.set('text',f'BS_DAMAGE_{n}_{d}_M{m}')
        elif node.tag=='m_XLPPath':node.set('text','BS_DamagedWorld.xlp')
        elif node.tag=='m_BLPPackage':node.set('text','BS_DamagedWorld')
    collection.append(e)
write(art,mod/'ArtDefs/WonderMovie.artdef')
buildings=ET.parse(mod/'ArtDefs/Buildings.artdef')
collection=buildings.find('m_RootCollections/Element')
template=next(e for e in collection.findall('Element')if e.find('m_Name').get('text')=='BUILDING_BS_DECK_1_0')
for e in list(collection.findall('Element')):
    if e.find('m_Name').get('text').startswith('BUILDING_BS_DAMAGED_'):collection.remove(e)
for t,n,d,m,s,legacy in variants:
    e=copy.deepcopy(template);e.find('m_Name').set('text',t);collection.append(e)
write(buildings,mod/'ArtDefs/Buildings.artdef')
dep=ET.parse(mod/'BridgeSpan.dep')
for lib in dep.findall('LibraryDependencies/Element'):
    if lib.find('LibraryName').get('text')=='WonderMovie':
        packages=lib.find('PackageDependencies')
        if not any(e.get('text')=='BS_DamagedWorld.blp'for e in packages):ET.SubElement(packages,'Element',text='BS_DamagedWorld.blp')
write(dep,mod/'BridgeSpan.dep')
info=ET.parse(mod/'BridgeSpan.modinfo');actions=info.find('InGameActions')
for tag,ident,file in [('UpdateDatabase','BS_Damage','Damage.sql'),('UpdateText','BS_DamageText','DamageText.xml'),('UpdateIcons','BS_DamageIcons','DamageIcons.sql')]:
    if actions.find(f"{tag}[@id='{ident}']")is None:
        action=ET.SubElement(actions,tag,id=ident,criteria='GS');ET.SubElement(ET.SubElement(action,'Properties'),'LoadOrder').text='2000002';ET.SubElement(action,'File').text=file
imports=actions.find("ImportFiles[@id='BS_Lua']")
if not any(e.text=='BridgeSpan_Damage.lua'for e in imports.findall('File')):ET.SubElement(imports,'File').text='BridgeSpan_Damage.lua'
files=info.find('Files')
damage_files=['Damage.sql','DamageIcons.sql','DamageText.xml','BridgeSpan_Damage.lua','Platforms/Windows/BLPs/BS_DamagedWorld.blp']
damage_files += [p.relative_to(mod).as_posix() for p in sorted((mod/'Platforms/Windows/BLPs/SHARED_DATA').glob('*BS_Damage_*'))]
assert len(damage_files)==21, 'Stage all 16 cooked damage textures before generating the manifest'
for file in damage_files:
    if not any(e.text==file for e in files):ET.SubElement(files,'File').text=file
write(info,mod/'BridgeSpan.modinfo')
print('Bound',len(variants),'damage components and',3*SLOTS,'city repair projects')
